import numpy as np

#Element-wise arithmetic

array1 = np.array([1,2,3,4])
array2 = np.array([5,6,7,8])

print(f"Calculate + each row: {array1 + array2}")
print(f"Calculate - each row: {array1 - array2}")
print(f"Calculate * each row: {array1 * array2}")
print(f"Calculate / each row: {array1 / array2}")
print(f"Calculate ** each row: {array1 ** array2}")